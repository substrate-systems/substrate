// Copies the assistant instruction blocks out of the Exomem repo's
// docs/prominence.md into src/app/exomem/home/instruction-blocks.generated.ts,
// and records the Exomem commit they came from.
//
//   npm run sync:instruction-blocks -- <path-to-exomem-repo>
//
// Home hands these blocks to a Cloud user to paste into an assistant that has no
// Exomem plugin. The doc warns that a shortened capture list silently drops
// whole classes of capture, so the blocks are copied byte for byte, never
// retyped. The doc is read from the repo's HEAD commit, not its working tree, so
// the commit written to the generated file is exactly the text it holds.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import remarkParse from "remark-parse";
import { unified } from "unified";

const DOC_PATH = "docs/prominence.md";
const OUTPUT_PATH = fileURLToPath(
  new URL("../src/app/exomem/home/instruction-blocks.generated.ts", import.meta.url)
);

// The four levels are a closed set that the doc's own level table fixes, so the
// level word that starts each heading is a sound key. It is not free text.
const LEVELS = ["off", "light", "balanced", "maximal"];

function git(repo, ...args) {
  return execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" });
}

function textOf(node) {
  if (typeof node.value === "string") return node.value;
  return (node.children ?? []).map(textOf).join("");
}

function extractBlocks(markdown) {
  const { children } = unified().use(remarkParse).parse(markdown);
  const blocks = {};

  children.forEach((node, index) => {
    if (node.type !== "heading" || node.depth !== 3) return;
    const level = textOf(node).trim().split(/\s+/)[0].toLowerCase();
    if (!LEVELS.includes(level)) return;
    if (level in blocks) throw new Error(`${DOC_PATH} has two "${level}" level headings`);

    for (const next of children.slice(index + 1)) {
      if (next.type === "heading" && next.depth <= 3) break;
      if (next.type === "code") {
        blocks[level] = next.value;
        return;
      }
    }
    throw new Error(`${DOC_PATH}: the "${level}" heading is not followed by a fenced block`);
  });

  const missing = LEVELS.filter((level) => !blocks[level]);
  if (missing.length > 0) {
    throw new Error(`${DOC_PATH} has no block for: ${missing.join(", ")}`);
  }
  return blocks;
}

function render(blocks, commit) {
  const entries = LEVELS.map((level) => `  ${level}: ${JSON.stringify(blocks[level])},`);
  return [
    "// Generated by scripts/sync-exomem-instruction-blocks.mjs. Do not edit by hand.",
    "// Regenerate: npm run sync:instruction-blocks -- <path-to-exomem-repo>",
    "",
    "export const INSTRUCTION_BLOCKS_SOURCE = {",
    '  repo: "exomem",',
    `  path: ${JSON.stringify(DOC_PATH)},`,
    `  commit: ${JSON.stringify(commit)},`,
    "} as const;",
    "",
    "export const INSTRUCTION_BLOCKS = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

async function main(repo) {
  if (!repo) throw new Error("usage: sync-exomem-instruction-blocks.mjs <path-to-exomem-repo>");
  const commit = git(repo, "rev-parse", "HEAD").trim();
  if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error(`unexpected commit from git: ${commit}`);
  const blocks = extractBlocks(git(repo, "show", `HEAD:${DOC_PATH}`));
  // Format with the repo's Prettier so `npm run format:check` accepts the file.
  const options = await resolveConfig(OUTPUT_PATH);
  writeFileSync(
    OUTPUT_PATH,
    await format(render(blocks, commit), { ...options, filepath: OUTPUT_PATH })
  );
  const lengths = LEVELS.map((level) => `${level}=${blocks[level].length}`).join(" ");
  console.log(`wrote ${OUTPUT_PATH}\n  exomem ${commit}\n  block lengths: ${lengths}`);
}

main(process.argv[2]).catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
